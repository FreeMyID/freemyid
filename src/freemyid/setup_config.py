"""`freemyid setup --from config.yaml`: non-interactive setup from a versioned YAML file.

OWNER: automation-engineer (CLI v0.2). Schema: schema/setup-config.schema.json (generated by
tools/gen_schema.py from :class:`SetupConfig`). Example: docs/examples/setup-config.example.yaml.

The file is turned into the same wizard Draft and goes through the same validators as the
web and terminal wizards (``wizard.draft.apply_step``), so the rules can never drift apart.
Passwords are never written in the file: the YAML names an environment variable or a file.
Consent stays explicit: ``consent.agreed: true`` plus a typed ``signed_name``, and the CLI
shows what will happen and needs ``--yes`` or an interactive confirm.
"""
from __future__ import annotations

import os
from datetime import date
from pathlib import Path
from typing import TYPE_CHECKING, Any, Literal

import yaml
from pydantic import BaseModel, ConfigDict, Field, ValidationError, model_validator

if TYPE_CHECKING:  # pragma: no cover
    from .wizard.draft import Draft

SETUP_CONFIG_VERSION = 1
MAX_ADDRESSES = 4     # the wizard's limit
MAX_FILE_BYTES = 256 * 1024


class _M(BaseModel):
    model_config = ConfigDict(extra="forbid")


class SetupConsent(_M):
    agreed: bool = Field(description="Must be true: you have read and agree to the consent "
                         "text that `freemyid setup --from` prints")
    signed_name: str = Field(min_length=1, description="Full name of the person giving "
                             "permission, typed as a signature")
    basis: Literal["self", "guardian_of_minor", "authorized_agent"] = Field(
        default="self", description="self = I am this person; guardian_of_minor = parent or "
        "legal guardian of someone under 18; authorized_agent = signed written permission")
    authorization_file: str | None = Field(
        default=None, description="Signed authorization form (PDF/image), required for "
        "authorized_agent. Relative paths are relative to this YAML file")


class SetupName(_M):
    first: str = Field(min_length=1)
    middle: str | None = None
    last: str = Field(min_length=1)
    suffix: str | None = None


class SetupAddress(_M):
    street: str | None = None
    city: str = Field(min_length=1)
    state: str = Field(pattern=r"^[A-Za-z]{2}$", description="2-letter US state, e.g. IL")
    zip: str | None = None
    current: bool = False


class SetupPerson(_M):
    label: str | None = Field(default=None, description="What to call them on screen, e.g. "
                              "'Mom'. Defaults to the first name")
    name: SetupName
    nicknames: list[str] = []
    previous_names: list[str] = Field(default=[], description="Full previous/maiden names")
    birth_year: int | None = Field(default=None, ge=1900, description="Only the year is kept")
    age: int | None = Field(default=None, ge=0, le=130, description="If birth_year is unknown")
    addresses: list[SetupAddress] = Field(min_length=1, max_length=MAX_ADDRESSES)
    phones: list[str] = []
    emails: list[str] = Field(default=[], description="Personal emails, used only to "
                              "recognize listings, never sent anywhere")
    relatives: list[str] = []


class SetupPermissions(_M):
    allow_id_upload: bool = False
    allow_account_creation: bool = False
    allow_phone_disclosure: bool = False


class SetupMailbox(_M):
    provider: Literal["gmail", "yahoo", "icloud", "proton_bridge", "other"]
    address: str = Field(description="The dedicated removal mailbox address")
    username: str | None = Field(default=None, description="Login name if not the address")
    password_env: str | None = Field(default=None, description="Name of an environment "
                                     "variable holding the app password")
    password_file: str | None = Field(default=None, description="File holding the app "
                                      "password (first line). Keep it chmod 600")
    imap_host: str | None = None
    imap_port: int | None = Field(default=None, ge=1, le=65535)
    imap_ssl: bool | None = None
    imap_starttls: bool | None = None
    smtp_host: str | None = None
    smtp_port: int | None = Field(default=None, ge=1, le=65535)
    smtp_starttls: bool | None = None
    tls_cert_sha256: str | None = Field(
        default=None, pattern=r"^[0-9A-Fa-f:]{64,95}$",
        description="Proton Mail Bridge only: the certificate fingerprint you approved")

    @model_validator(mode="before")
    @classmethod
    def _no_inline_password(cls, v: Any) -> Any:
        if isinstance(v, dict) and "password" in v:
            raise ValueError("never put the password in the file; use password_env or "
                             "password_file")
        return v

    @model_validator(mode="after")
    def _one_password_source(self) -> SetupMailbox:
        if bool(self.password_env) == bool(self.password_file):
            raise ValueError("give exactly one of password_env or password_file")
        return self


class SetupSchedule(_M):
    weekly_recheck: bool = True
    weekday: int = Field(default=6, ge=0, le=6, description="0=Mon .. 6=Sun")
    hour: int = Field(default=10, ge=0, le=23)
    install_job: bool = Field(default=False, description="Also install the background job "
                              "(same as `freemyid schedule install`)")


class SetupConfig(_M):
    """Free My ID setup file, version 1. One file = one person."""
    version: Literal[1] = Field(description="Setup file format version")
    consent: SetupConsent
    person: SetupPerson
    permissions: SetupPermissions = SetupPermissions()
    mailbox: SetupMailbox | None = None
    email_mode: Literal["approve_each", "auto"] = "approve_each"
    schedule: SetupSchedule = SetupSchedule()


class SetupFileError(ValueError):
    """The setup file is unreadable or invalid. `problems` are plain-language lines."""

    def __init__(self, problems: list[str]) -> None:
        super().__init__("; ".join(problems))
        self.problems = problems


def load(path: Path) -> SetupConfig:
    path = Path(path)
    try:
        if path.stat().st_size > MAX_FILE_BYTES:
            raise SetupFileError([f"{path.name} is too large to be a setup file"])
        raw = yaml.safe_load(path.read_text(encoding="utf-8"))
    except OSError as e:
        raise SetupFileError([f"cannot read {path}: {type(e).__name__}"]) from e
    except yaml.YAMLError as e:
        raise SetupFileError([f"{path.name} is not valid YAML"]) from e
    if not isinstance(raw, dict):
        raise SetupFileError([f"{path.name} should be a YAML mapping (key: value)"])
    try:
        return SetupConfig.model_validate(raw)
    except ValidationError as e:
        # field paths and messages only: never echo the values (they are PII)
        raise SetupFileError([f"{'.'.join(str(x) for x in err['loc']) or 'file'}: {err['msg']}"
                              for err in e.errors(include_input=False)]) from e


def _resolve(base: Path, p: str) -> Path:
    q = Path(os.path.expanduser(p))
    return q if q.is_absolute() else base / q


def read_password(mb: SetupMailbox, base: Path) -> str:
    if mb.password_env:
        pw = os.environ.get(mb.password_env, "")
        if not pw:
            raise SetupFileError([(f"mailbox.password_env: environment variable "
                                  f"{mb.password_env} is not set")])
        return pw
    assert mb.password_file
    f = _resolve(base, mb.password_file)
    try:
        lines = f.read_text(encoding="utf-8").splitlines()
    except OSError as e:
        raise SetupFileError([f"mailbox.password_file: cannot read it ({type(e).__name__})"]
                             ) from e
    pw = lines[0].strip() if lines else ""
    if not pw:
        raise SetupFileError(["mailbox.password_file: the file is empty"])
    return pw


def _flag(b: bool | None) -> str:
    return "1" if b else ""


def to_draft(cfg: SetupConfig, base: Path) -> Draft:
    """Build a wizard Draft through the wizard's own validators. Raises SetupFileError."""
    from .wizard import draft as dr
    from .wizard.flows import _Form

    d = dr.Draft()
    problems: list[str] = []

    def step(name: str, form: dict[str, Any], files: dict | None = None) -> None:
        problems.extend(f"{name}: {e}" for e in dr.apply_step(d, name, _Form(form), files))

    c = cfg.consent
    if not c.agreed:
        problems.append("consent.agreed must be true (read the consent text first)")
    files = None
    if c.authorization_file:
        f = _resolve(base, c.authorization_file)
        try:
            files = {"authorization": (f.name, f.read_bytes())}
        except OSError as e:
            problems.append(f"consent.authorization_file: cannot read it ({type(e).__name__})")
    elif c.basis == "authorized_agent":
        problems.append("consent.authorization_file is required for authorized_agent")
    step("consent", {"basis": c.basis, "attested_by": c.signed_name,
                     "ack": "1" if c.agreed else ""}, files)

    pp = cfg.person
    step("name", {"first": pp.name.first, "middle": pp.name.middle or "",
                  "last": pp.name.last, "suffix": pp.name.suffix or "",
                  "label": pp.label or "", "nicknames": "\n".join(pp.nicknames),
                  "previous_names": "\n".join(pp.previous_names)})
    addr: dict[str, Any] = {}
    for i, a in enumerate(pp.addresses):
        addr.update({f"street{i}": a.street or "", f"city{i}": a.city,
                     f"state{i}": a.state, f"zip{i}": a.zip or ""})
    cur = next((i for i, a in enumerate(pp.addresses) if a.current), 0)
    addr["current"] = str(cur)
    step("address", addr)
    about: dict[str, Any] = {"phones": "\n".join(pp.phones), "emails": "\n".join(pp.emails),
                             "relatives": "\n".join(pp.relatives)}
    if pp.birth_year is not None:
        if pp.birth_year > date.today().year:
            problems.append("person.birth_year is in the future")
        about["birth_year"] = str(pp.birth_year)
    elif pp.age is not None:
        about["age"] = str(pp.age)
    step("about", about)
    perm = cfg.permissions
    step("permissions", {k: _flag(getattr(perm, k)) for k in
                         ("allow_id_upload", "allow_account_creation",
                          "allow_phone_disclosure")})

    mb = cfg.mailbox
    if mb is None:
        step("mailbox", {"provider": "skip"})
    else:
        try:
            pw = read_password(mb, base)
        except SetupFileError as e:
            problems.extend(e.problems)
            pw = ""
        if mb.tls_cert_sha256:
            d.tls_pin = mb.tls_cert_sha256.replace(":", "").lower()
        form: dict[str, Any] = {"provider": mb.provider, "address": mb.address,
                                "username": mb.username or "", "password": pw}
        hosts = ("imap_host", "smtp_host", "imap_port", "smtp_port", "imap_ssl",
                 "imap_starttls", "smtp_starttls")
        if mb.provider == "other" or any(getattr(mb, k) is not None for k in hosts):
            preset = dr.PRESETS[mb.provider]
            form["custom_hosts"] = "1"
            for k in hosts:
                v = getattr(mb, k)
                v = preset.get(k) if v is None else v
                form[k] = _flag(v) if isinstance(v, bool) or k.endswith(("ssl", "tls")) \
                    else ("" if v is None else str(v))
        if pw:
            step("mailbox", form)
        for i, msg in enumerate(problems):
            if msg.startswith("mailbox:") and "security code" in msg:
                problems[i] = ("mailbox: Proton Mail Bridge needs tls_cert_sha256 (approve "
                               "the certificate once in the wizard, then copy its fingerprint)")
    step("email", {"email_mode": cfg.email_mode})
    step("schedule", {"weekly_recheck": _flag(cfg.schedule.weekly_recheck)})
    d.weekday, d.hour = cfg.schedule.weekday, cfg.schedule.hour
    if problems:
        raise SetupFileError(problems)
    return d


def plan_lines(cfg: SetupConfig) -> list[str]:
    """What will happen, in plain words. Shows only what the person wrote to be shown."""
    from .wizard import draft as dr
    pp = cfg.person
    label = pp.label or pp.name.first
    lines = [f"Free My ID will save one person on this computer: {label}.",
             f"  {len(pp.addresses)} address(es), {len(pp.phones)} phone(s), "
             f"{len(pp.emails)} email(s), {len(pp.relatives)} relative(s); "
             + ("birth year given." if pp.birth_year else
                "age given." if pp.age is not None else "no birth year."),
             "  Removal mailbox: " + (cfg.mailbox.provider if cfg.mailbox else
                                      "none (email removals stay off)") + ".",
             "  Emails to brokers: " + ("sent automatically" if cfg.email_mode == "auto"
                                         else "each one waits for your approval") + ".",
             "  Background re-checks: " + (
                 ("weekly; the job will be installed now" if cfg.schedule.install_job
                  else "weekly once you run `freemyid schedule install`")
                 if cfg.schedule.weekly_recheck else "off") + ".",
             ("  Practice mode stays as it is: no removal requests go out until real submissions are "
             "enabled (`freemyid config enable-submissions`)."),
             "",
             f"Permission ({dr.BASIS_LABELS[cfg.consent.basis]}):"]
    lines += [f"  - {t}" for t in dr.CONSENT_TEXT]
    lines.append(f"Signed: {cfg.consent.signed_name}")
    return lines


def find_existing(store: Any, label: str) -> Any:
    k = label.strip().lower()
    return next((p for p in store.list_profiles() if p.label.strip().lower() == k), None)
