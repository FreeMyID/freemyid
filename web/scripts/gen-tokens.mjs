// Turn ../site_src/tokens.yaml (the design tokens, one source of truth) into two files:
//   src/styles/tokens.css  framework-neutral CSS custom properties (--fmi-*), light and dark.
//                          Plain CSS: the desktop app / installer can import this same file later.
//   src/styles/theme.css   the Tailwind v4 `@theme inline` mapping onto those properties.
// Fails if any contrast pair drops below its minimum in either theme (same rule as
// tools/build_site.py check_contrast). Deterministic output; both files are committed.
// `node scripts/gen-tokens.mjs --check` fails if the committed files are stale (CI).
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { parse } from "yaml";

const src = new URL("../../site_src/tokens.yaml", import.meta.url);
const outTokens = new URL("../src/styles/tokens.css", import.meta.url);
const outTheme = new URL("../src/styles/theme.css", import.meta.url);
const t = parse(readFileSync(src, "utf8"));

function lum(hex) {
  const h = hex.replace("#", "");
  const c = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
  const l = c.map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * l[0] + 0.7152 * l[1] + 0.0722 * l[2];
}
export function contrast(a, b) {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
}

const errors = [];
for (const [fg, bg, min] of t.pairs) {
  ["light", "dark"].forEach((theme, i) => {
    const r = contrast(t.color[fg][i], t.color[bg][i]);
    if (r < min) errors.push(`contrast ${theme}: ${fg} on ${bg} = ${r.toFixed(2)} < ${min}`);
  });
}
if (errors.length) {
  for (const e of errors) console.error("ERROR:", e);
  process.exit(1);
}

// type scale names (tokens.yaml "step" keys -> readable names)
const STEP = { "-1": "small", 0: "body", 1: "lead", 2: "h3", 3: "h2", 4: "h1", 5: "display" };
const colors = Object.entries(t.color);
const HEAD = "/* GENERATED by web/scripts/gen-tokens.mjs from site_src/tokens.yaml. Do not edit. */";

// ---------------------------------------------------------------- tokens.css (framework-neutral)
const T = [HEAD,
  "/* Free My ID design tokens as plain CSS custom properties. Works in any page or app:",
  "   colors follow the OS theme via light-dark(); <html data-theme=\"light|dark\"> overrides it. */",
  ":root {",
  "  color-scheme: light dark;"];
for (const [n, [light, dark]] of colors) T.push(`  --fmi-color-${n}: light-dark(${light}, ${dark});`);
for (const [k, v] of Object.entries(t.space)) T.push(`  --fmi-space-${k}: ${v};`);
for (const [k, v] of Object.entries(t.step)) T.push(`  --fmi-text-${STEP[k]}: ${v};`);
for (const [k, v] of Object.entries(t.radius)) T.push(`  --fmi-radius-${k}: ${v};`);
T.push(`  --fmi-font-sans: ${t.misc["font-body"]};`);
T.push(`  --fmi-font-mono: ${t.misc["font-mono"]};`);
for (const k of ["shadow-1", "shadow-2", "shadow-3"]) T.push(`  --fmi-${k}: ${t.misc[k]};`);
T.push(`  --fmi-wrap: ${t.misc.wrap};`, `  --fmi-measure: ${t.misc.measure};`,
  `  --fmi-tap: ${t.misc.tap};`, `  --fmi-gutter: ${t.misc.gutter};`, "}");
T.push(':root[data-theme="light"] { color-scheme: light; }', ':root[data-theme="dark"] { color-scheme: dark; }');
const plain = (i, pad) => colors.map(([n, v]) => `${pad}--fmi-color-${n}: ${v[i]};`).join("\n");
T.push("/* Browsers without light-dark() (before ~2024): plain values plus the data-theme override. */");
T.push("@supports not (color: light-dark(#000, #fff)) {");
T.push("  :root {\n" + plain(0, "    ") + "\n  }");
T.push("  @media (prefers-color-scheme: dark) {");
T.push('    :root:not([data-theme="light"]) {\n' + plain(1, "      ") + "\n    }");
T.push("  }");
T.push('  :root[data-theme="dark"] {\n' + plain(1, "    ") + "\n  }");
T.push("}");

// ---------------------------------------------------------------- theme.css (Tailwind mapping)
const W = [HEAD, "/* Tailwind v4 theme: every utility reads a --fmi-* property from tokens.css. */", "@theme inline {",
  "  --color-*: initial;", "  --color-transparent: transparent;", "  --color-current: currentColor;"];
for (const [n] of colors) W.push(`  --color-${n}: var(--fmi-color-${n});`);
for (const k of Object.keys(t.space)) W.push(`  --spacing-${k}: var(--fmi-space-${k});`);
for (const k of Object.keys(t.step)) W.push(`  --text-${STEP[k]}: var(--fmi-text-${STEP[k]});`);
for (const k of Object.keys(t.radius)) W.push(`  --radius-${k}: var(--fmi-radius-${k});`);
W.push("  --font-sans: var(--fmi-font-sans);", "  --font-mono: var(--fmi-font-mono);");
for (const k of ["1", "2", "3"]) W.push(`  --shadow-${k}: var(--fmi-shadow-${k});`);
W.push("  --container-wrap: var(--fmi-wrap);", "  --container-measure: var(--fmi-measure);",
  "  --spacing-tap: var(--fmi-tap);", "  --spacing-gutter: var(--fmi-gutter);", "}");

const files = [[outTokens, T.join("\n") + "\n"], [outTheme, W.join("\n") + "\n"]];
if (process.argv.includes("--check")) {
  const stale = files.filter(([u, s]) => !existsSync(u) || readFileSync(u, "utf8") !== s);
  for (const [u] of stale) console.error("ERROR: stale", u.pathname, "(run pnpm tokens)");
  if (stale.length) process.exit(1);
} else {
  for (const [u, s] of files) writeFileSync(u, s);
}
console.log(`tokens: ${colors.length} colors, ${t.pairs.length} contrast pairs OK in light and dark`);
