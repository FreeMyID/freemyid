// Turn ../site_src/tokens.yaml (the v2 design tokens, one source of truth) into the Tailwind v4
// theme at src/styles/tokens.css, and fail if any contrast pair drops below its minimum in
// either theme (same rule as tools/build_site.py check_contrast). Deterministic output.
import { readFileSync, writeFileSync } from "node:fs";
import { parse } from "yaml";

const src = new URL("../../site_src/tokens.yaml", import.meta.url);
const out = new URL("../src/styles/tokens.css", import.meta.url);
const t = parse(readFileSync(src, "utf8"));

function lum(hex) {
  const h = hex.replace("#", "");
  const c = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
  const l = c.map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * l[0] + 0.7152 * l[1] + 0.0722 * l[2];
}
export function contrast(a, b) {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
}

const errors = [];
for (const [fg, bg, min] of t.pairs) {
  ["light", "dark"].forEach((theme, i) => {
    const r = contrast(t.color[fg][i], t.color[bg][i]);
    if (r < min) errors.push(`contrast ${theme}: ${fg} on ${bg} = ${r.toFixed(2)} < ${min}`);
  });
}
if (errors.length) {
  for (const e of errors) console.error("ERROR:", e);
  process.exit(1);
}

// type scale names (tokens.yaml "step" keys -> readable Tailwind text-* names)
const STEP = { "-1": "small", 0: "body", 1: "lead", 2: "h3", 3: "h2", 4: "h1", 5: "display" };
const colors = Object.entries(t.color);
const L = [];
L.push("/* GENERATED by scripts/gen-tokens.mjs from site_src/tokens.yaml. Do not edit. */");
L.push("@theme {");
L.push("  --color-*: initial;");
L.push("  --color-transparent: transparent;");
L.push("  --color-current: currentColor;");
for (const [n, [light, dark]] of colors) L.push(`  --color-${n}: light-dark(${light}, ${dark});`);
for (const [k, v] of Object.entries(t.space)) L.push(`  --spacing-${k}: ${v};`);
for (const [k, v] of Object.entries(t.step)) L.push(`  --text-${STEP[k]}: ${v};`);
for (const [k, v] of Object.entries(t.radius)) L.push(`  --radius-${k}: ${v};`);
L.push(`  --font-sans: ${t.misc["font-body"]};`);
L.push(`  --font-mono: ${t.misc["font-mono"]};`);
for (const k of ["shadow-1", "shadow-2", "shadow-3"]) L.push(`  --shadow-${k.slice(-1)}: ${t.misc[k]};`);
L.push(`  --container-wrap: ${t.misc.wrap};`);
L.push(`  --container-measure: ${t.misc.measure};`);
L.push(`  --spacing-tap: ${t.misc.tap};`);
L.push(`  --spacing-gutter: ${t.misc.gutter};`);
L.push("}");
// Browsers without light-dark() (before ~2024) get plain values, plus the data-theme override.
const plain = (i, pad) => colors.map(([n, v]) => `${pad}--color-${n}: ${v[i]};`).join("\n");
L.push("@supports not (color: light-dark(#000, #fff)) {");
L.push("  :root {\n" + plain(0, "    ") + "\n  }");
L.push("  @media (prefers-color-scheme: dark) {");
L.push('    :root:not([data-theme="light"]) {\n' + plain(1, "      ") + "\n    }");
L.push("  }");
L.push('  :root[data-theme="dark"] {\n' + plain(1, "    ") + "\n  }");
L.push("}");
writeFileSync(out, L.join("\n") + "\n");
console.log(`tokens.css: ${colors.length} colors, ${t.pairs.length} contrast pairs OK in light and dark`);
